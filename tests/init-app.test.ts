import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";

const copiedFiles = [
  "config/data-projects.json",
  "scripts/app-spec.mjs",
  "scripts/data-access.mjs",
  "scripts/data-preparation.mjs",
  "scripts/init-app.mjs",
];

const operationalFiles = [
  "package.json",
  "package-lock.json",
  ".env.example",
  "app.yaml",
  "databricks.yml",
  "data/databricks.yml",
  "data/resources.generated.yml",
  "config/app-spec.yml",
  "config/data-access.json",
  "config/data-projects.json",
  "docs/product-brief.md",
  "resources/data-access.generated.yml",
  ".github/workflows/deploy.yml",
];

async function prepareRoot(prefix: string): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), prefix));
  for (const file of copiedFiles) {
    const destination = join(root, file);
    await mkdir(dirname(destination), { recursive: true });
    await copyFile(file, destination);
  }
  const fixtures: Record<string, string> = {
    "package.json": JSON.stringify({ name: "__PACKAGE_NAME__", version: "0.1.0" }, null, 2),
    "package-lock.json": JSON.stringify({ name: "__PACKAGE_NAME__", version: "0.1.0", lockfileVersion: 3, packages: { "": { name: "__PACKAGE_NAME__", version: "0.1.0" } } }, null, 2),
    ".env.example": "APP_NAME=\"__APP_NAME__\"\nAPP_DESCRIPTION=\"__APP_DESCRIPTION__\"\nDATABRICKS_HOST=https://3070470996474403.3.gcp.databricks.com\nDATABRICKS_CONFIG_PROFILE=valiuz-analytics-dev\nDATABRICKS_SQL_WAREHOUSE_ID=ab362e9710498a08\nDATABRICKS_CATALOG=__DATABRICKS_CATALOG__\nDATABRICKS_SCHEMA=__DATABRICKS_SCHEMA__\n",
    "app.yaml": "env:\n  - name: APP_NAME\n    value: \"__APP_NAME__\"\n  - name: APP_DESCRIPTION\n    value: \"__APP_DESCRIPTION__\"\n  - name: DATABRICKS_CATALOG\n    value: \"__DATABRICKS_CATALOG__\"\n  - name: DATABRICKS_SCHEMA\n    value: \"__DATABRICKS_SCHEMA__\"\n",
    "databricks.yml": "bundle:\n  name: \"__APP_NAME__\"\nvariables:\n  app_description:\n    default: \"__APP_DESCRIPTION__\"\n  sql_warehouse_id:\n    default: ab362e9710498a08\n  git_repo_url:\n    default: \"__GIT_REPOSITORY_URL__\"\n  can_use_group:\n    default: \"__CAN_USE_GROUP__\"\n  can_manage_group:\n    default: \"__CAN_MANAGE_GROUP__\"\n  prod_root_path:\n    default: \"__DATABRICKS_PROD_ROOT_PATH__\"\ntargets:\n  prod:\n    workspace:\n      host: https://3070470996474403.3.gcp.databricks.com\n",
    "data/databricks.yml": "bundle:\n  name: \"__APP_NAME__-data\"\nvariables:\n  sql_warehouse_id:\n    default: ab362e9710498a08\ntargets:\n  prod:\n    workspace:\n      host: https://3070470996474403.3.gcp.databricks.com\n      root_path: \"__DATABRICKS_PROD_ROOT_PATH__/data\"\n",
    "data/resources.generated.yml": "# Generated by npm run data:prepare:render. Do not edit directly.\nresources: {}\n",
    "config/app-spec.yml": "version: 1\napp:\n  name: __PACKAGE_NAME__\n  type: dashboard\n  audience: À confirmer\n  decision: À confirmer\n  success: À confirmer\nfeatures: []\n",
    "config/data-access.json": "{\n  \"project\": \"__DATABRICKS_CATALOG__\",\n  \"sources\": []\n}\n",
    "docs/product-brief.md": "",
    "resources/data-access.generated.yml": "# Generated by npm run data:access:render. Do not edit directly.\nresources:\n  apps:\n    app:\n      resources:\n        - name: sql-warehouse\n          sql_warehouse:\n            id: ${var.sql_warehouse_id}\n            permission: CAN_USE\n",
    ".github/workflows/deploy.yml": "env:\n  APP_NAME: \"__APP_NAME__\"\n",
  };
  for (const [file, content] of Object.entries(fixtures)) {
    const destination = join(root, file);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, `${content}\n`, "utf8");
  }
  await mkdir(join(root, "data/contracts"), { recursive: true });
  await symlink(join(process.cwd(), "node_modules"), join(root, "node_modules"), "dir");
  return root;
}

test("bootstrap replaces all operational placeholders and keeps JSON valid", async () => {
  const root = await prepareRoot("databricks-app-init-");

  execFileSync(
    process.execPath,
    [
      "scripts/init-app.mjs",
      "sample-app",
      "--non-interactive",
      "--description", "Sample analytics app",
      "--warehouse", "warehouse-123",
      "--data-project", "dev-dtm-media-pm",
      "--schema", "sample_app",
      "--host", "https://dbc.example.cloud.databricks.com",
      "--repository-url", "https://github.com/example/sample-app",
      "--can-use-group", "analysts",
      "--can-manage-group", "app-admins",
    ],
    { cwd: root },
  );

  const rendered = await Promise.all(operationalFiles.map((file) => readFile(join(root, file), "utf8")));
  const renderedText = rendered.join("\n");
  assert.doesNotMatch(renderedText, /__[A-Z][A-Z_]+__/);
  assert.doesNotMatch(renderedText, /3070470996474403\.3\.gcp\.databricks\.com/);
  assert.doesNotMatch(renderedText, /ab362e9710498a08/);
  assert.match(renderedText, /sample-app/);
  assert.match(renderedText, /https:\/\/dbc\.example\.cloud\.databricks\.com/);
  assert.match(renderedText, /warehouse-123/);
  assert.match(renderedText, /dev-dtm-media-pm/);
  JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  JSON.parse(await readFile(join(root, "package-lock.json"), "utf8"));
});

test("bootstrap uses the shared Valiuz workspace and SQL warehouse defaults", async () => {
  const root = await prepareRoot("databricks-app-defaults-");

  execFileSync(
    process.execPath,
    [
      "scripts/init-app.mjs",
      "sample-app",
      "--non-interactive",
      "--schema", "sample_app",
    ],
    { cwd: root },
  );

  const environment = await readFile(join(root, ".env.example"), "utf8");
  const bundle = await readFile(join(root, "databricks.yml"), "utf8");
  const dataResources = await readFile(join(root, "resources/data-access.generated.yml"), "utf8");
  const renderedText = `${environment}\n${bundle}\n${dataResources}`;
  assert.match(renderedText, /https:\/\/3070470996474403\.3\.gcp\.databricks\.com/);
  assert.match(renderedText, /ab362e9710498a08/);
  assert.match(environment, /DATABRICKS_CONFIG_PROFILE=valiuz-analytics-dev/);
  assert.match(environment, /DATABRICKS_CATALOG=dev-dtm-operating/);
  assert.match(dataResources, /permission: CAN_USE/);
});

test("bootstrap rejects a data project outside the Valiuz allowlist", async () => {
  const root = await prepareRoot("databricks-app-invalid-project-");

  assert.throws(
    () =>
      execFileSync(
        process.execPath,
        [
          "scripts/init-app.mjs",
          "sample-app",
          "--non-interactive",
          "--data-project", "unmanaged-project",
          "--schema", "sample_app",
        ],
        { cwd: root, stdio: "pipe" },
      ),
    /Command failed/,
  );
});

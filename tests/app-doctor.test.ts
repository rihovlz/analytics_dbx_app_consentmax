import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";

const productBrief = "# Brief produit\n\n## Objectif et utilisateurs\n\n- Type : dashboard\n- Utilisateurs : Analyste\n- Décision à faciliter : Suivre les ventes\n- Critère de succès : Usage hebdomadaire\n\n## KPI, sources et fonctionnalités\n\nÀ confirmer avec la première tranche verticale.\n\n## Accès, confidentialité et exploitation\n\nÀ confirmer avant le premier accès à des données réelles.\n\n## Backlog\n\nConstruire et faire valider une tranche à la fois.\n";

test("app doctor reports the next useful action without exposing environment values", async () => {
  const root = await mkdtemp(join(tmpdir(), "app-doctor-"));
  const files = [
    "config/data-projects.json",
    "scripts/app-doctor.mjs",
    "scripts/app-spec.mjs",
    "scripts/data-access.mjs",
    "scripts/data-preparation.mjs",
  ];
  for (const file of files) {
    const destination = join(root, file);
    await mkdir(dirname(destination), { recursive: true });
    await copyFile(file, destination);
  }
  await mkdir(join(root, "config"), { recursive: true });
  await mkdir(join(root, "data/contracts"), { recursive: true });
  await mkdir(join(root, "docs"), { recursive: true });
  await mkdir(join(root, "resources"), { recursive: true });
  await writeFile(
    join(root, "resources/data-access.generated.yml"),
    "# Generated by npm run data:access:render. Do not edit directly.\nresources:\n  apps:\n    app:\n      resources:\n        - name: sql-warehouse\n          sql_warehouse:\n            id: ${var.sql_warehouse_id}\n            permission: CAN_USE\n",
    "utf8",
  );
  await writeFile(
    join(root, "data/resources.generated.yml"),
    "# Generated by npm run data:prepare:render. Do not edit directly.\nresources: {}\n",
    "utf8",
  );
  await writeFile(join(root, "package.json"), JSON.stringify({ name: "sample-app" }), "utf8");
  await writeFile(
    join(root, "config/app-spec.yml"),
    "version: 1\napp:\n  name: sample-app\n  type: dashboard\n  audience: Analyste\n  decision: Suivre les ventes\n  success: Usage hebdomadaire\nfeatures: []\n",
    "utf8",
  );
  await writeFile(join(root, "config/data-access.json"), JSON.stringify({ project: "dev-dtm-media-pm", sources: [] }), "utf8");
  await writeFile(join(root, "app.yaml"), "env:\n  - name: DATABRICKS_CATALOG\n    value: dev-dtm-media-pm\n", "utf8");
  await writeFile(join(root, ".env.example"), "DATABRICKS_CATALOG=dev-dtm-media-pm\n", "utf8");
  await writeFile(join(root, "docs/product-brief.md"), productBrief, "utf8");
  await symlink(join(process.cwd(), "node_modules"), join(root, "node_modules"), "dir");

  const command = spawnSync(process.execPath, ["scripts/app-doctor.mjs", "--json"], {
    cwd: root,
    encoding: "utf8",
    env: { ...process.env, PATH: "" },
  });
  assert.equal(command.status, 0, command.stderr);
  const results = JSON.parse(command.stdout) as Array<{ status: string; name: string; next?: string }>;
  assert.equal(results.some((item) => item.status === "fail"), false);
  assert.equal(results.find((item) => item.name === "Étape recommandée")?.next, "npm run data:init -- <nom>");
  assert.doesNotMatch(JSON.stringify(results), /DATABRICKS_TOKEN|CLIENT_SECRET/);
  assert.match(await readFile(join(root, "docs/product-brief.md"), "utf8"), /Suivre les ventes/);
});
